-- Question - 5
-- Slow Moving Inventory -- High Stock Available but low Sales 
 WITH CTE AS 
 (
SELECT SKU ,  STOCK_AVAILABLE , UNITS_SOLD ,
CASE 
      WHEN STOCK_AVAILABLE > 200 AND 
      UNITS_SOLD < 50 THEN "SLOW INVENTORY" 
      ELSE "NORMAL INVENTORY"
END AS INVENTORY_INSPECTION 
FROM FMCG
)
SELECT SKU ,  STOCK_AVAILABLE , UNITS_SOLD , INVENTORY_INSPECTION FROM CTE
WHERE INVENTORY_INSPECTION LIKE "%SLOW%" ;

