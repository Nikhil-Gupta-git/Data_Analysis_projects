-- Question - 10 

-- pivot revenue by channel

SELECT YEAR(`DATE`) AS YEAR,
	   MONTH(`DATE`) AS MONTH,
SUM(CASE 
       WHEN `CHANNEL` = 'RETAIL' 
       THEN UNITS_SOLD * SELLING_PRICE 
       ELSE 0 
	END) AS RETAIL_REVENUE ,
SUM(CASE 
       WHEN `CHANNEL` = 'DISCOUNT' 
       THEN UNITS_SOLD * SELLING_PRICE 
       ELSE 0 
	END) AS DISCOUNT_REVENUE ,
SUM(CASE 
	   WHEN `CHANNEL` = 'E-COMMERCE'  
       THEN UNITS_SOLD * SELLING_PRICE 
       ELSE 0 
	END) AS E_COMMERCE_REVENUE 
FROM FMCG 
GROUP BY 
    YEAR(`DATE`) ,
    MONTH(`DATE`)
ORDER BY YEAR,
	    MONTH ;