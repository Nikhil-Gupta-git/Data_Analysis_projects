 -- Question - 9
 -- Retail vs Ecommerce
 # on the basis of units sold

SELECT `CHANNEL` ,
CASE 
    WHEN `CHANNEL` = 'RETAIL' THEN SUM(UNITS_SOLD) 
    WHEN `CHANNEL` = 'E-COMMERCE' THEN SUM(UNITS_SOLD)
END AS TOTAL_UNITS_SOLD
FROM FMCG 
GROUP BY `CHANNEL` ;
-- FEEDBACK -- E-COMMERCE HAS MORE SALES THEN RETAIL 

-- ON THE BASIS OF DELIVERED_QTY 
SELECT `CHANNEL` ,
CASE 
    WHEN `CHANNEL` = 'RETAIL' THEN SUM(DELIVERED_QTY) 
    WHEN `CHANNEL` = 'E-COMMERCE' THEN SUM(DELIVERED_QTY)
END AS TOTAL_ITEM_DELIVERED 
FROM FMCG 
GROUP BY `CHANNEL` 
ORDER BY TOTAL_ITEM_DELIVERED DESC;

